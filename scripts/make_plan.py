def to_md(p):
    L = ["# 訓練計畫（2026-10-01 ～ 2026-12-31）：半馬 → 10K 49:59", "",
         "> 10/25 半程馬拉松 21.1 km（目標 1:59:46，配速 5:40/km、10.6 km/h）｜10/25 之後主目標：12/27 10K 自我測試 49:59 以內（4:58/km、12.1 km/h）｜跑步機一律 0% 坡度", "",
         "## 重要提醒", "", p["caveat"], "", "## 背景與假設", ""]
    L += [f"- {a}" for a in p["assumptions"]]
    L += ["", "## 逐日計畫", "", "| 日期 | 星期 | 內容 | 距離 (km) | 路跑配速 | 跑步機（0%） | 說明 |", "|---|---|---|---|---|---|---|"]
    for x in p["days"]:
        km = "—" if not x["km"] else (f'{x["km"]:g}')
        L.append(f'| {x["date"]} | {x["weekday"]} | {x["type"]} | {km} | {x["pace"] or "—"} | {x["treadmill"] or "—"} | {x["note"]} |')
    L += ["", "## 每週跑量（週一～週日；10/25 半馬當天不計入）", ""]
    for k, v in p["weekly_km"].items():
        ph = p["week_phase"].get(k)
        L.append(f"- 週起 {k}：{v:.1f} km" + (f"（{ph}）" if ph else "") + ("（含 10/1 起的部分週）" if k == "2026-09-28" else ""))
    L += ["", "## " + p["race_title"], ""]
    L += [f"{i}. {s}" for i, s in enumerate(p["race_plan"], 1)]
    L += ["", "## " + p["test_title"], ""]
    L += [f"{i}. {s}" for i, s in enumerate(p["test_plan"], 1)]
    c = p["checkin"]
    L += ["", "## " + c["title"], ""] + [f"- {x}" for x in c["items"]]
    L += ["", "長期目標：" + "；".join(c["goals"]), "", "安全規則：" + "；".join(c["rules"])]
    return "\n".join(L) + "\n"

