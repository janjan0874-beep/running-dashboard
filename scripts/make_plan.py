def week_key(d):
    return d - dt.timedelta(days=d.weekday())

def build():
    days = []
    for d, kind, t, km, pace, tm, note in DAYS:
        dd = dt.date.fromisoformat(d)
        days.append(dict(date=d, weekday="週"+WD[dd.weekday()], kind=kind, type=t, km=km, pace=pace, treadmill=tm, note=note,
                         week=week_key(dd).isoformat()))
    weeks = {}
    for x in days:
        if x["date"] != RACE.isoformat():
            weeks[x["week"]] = weeks.get(x["week"], 0) + x["km"]
    return dict(race_date=RACE.isoformat(), race_name="半程馬拉松 21.1 km", days=days,
                weekly_km={k: round(v, 1) for k, v in weeks.items()},
                assumptions=ASSUMPTIONS, race_plan=RACE_PLAN, caveat=CAVEAT, checkin=CHECKIN, goal_pace=GOAL)

def to_md(p):
    L = ["# 半程馬拉松最後 25 天計畫（2026-10-01 ～ 2026-10-25）", "",
         "> 比賽日：2026-10-25 半程馬拉松 21.1 km｜目標：破 2 小時（5:41/km，目標非保證）｜跑步機一律 0% 坡度", "",
         "## 重要提醒", "", p["caveat"], "", "## 背景與假設", ""]
    L += [f"- {a}" for a in p["assumptions"]]
    L += ["", "## 逐日計畫", "", "| 日期 | 星期 | 內容 | 距離 (km) | 路跑配速 | 跑步機（0%） | 說明 |", "|---|---|---|---|---|---|---|"]
    for x in p["days"]:
        km = "—" if not x["km"] else (f'{x["km"]:g}')
        L.append(f'| {x["date"]} | {x["weekday"]} | {x["type"]} | {km} | {x["pace"] or "—"} | {x["treadmill"] or "—"} | {x["note"]} |')
    L += ["", "## 每週跑量（週一～週日；不含比賽日）", ""]
    for k, v in p["weekly_km"].items():
        L.append(f"- 週起 {k}：{v:g} km" + ("（含 10/1 起的部分週）" if k == "2026-09-28" else ""))
    L += ["", "## 比賽日策略", ""]
    L += [f"{i}. {s}" for i, s in enumerate(p["race_plan"], 1)]
    c = p["checkin"]
    L += ["", "## " + c["title"], ""] + [f"- {x}" for x in c["items"]]
    L += ["", "長期目標：" + "；".join(c["goals"]), "", "安全規則：" + "；".join(c["rules"])]
    return "\n".join(L) + "\n"

