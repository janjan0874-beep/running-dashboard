def next_goal(today):
    """今天（含）之後最近的目標；全部過了就回傳最後一個。"""
    for g in GOALS:
        if g["date"] >= today.isoformat():
            return g
    return GOALS[-1]

def week_key(d):
    return d - dt.timedelta(days=d.weekday())

def build(apply_adjust=True, check_actual=True, today=None):
    """apply_adjust：套用 adjust_week.py 寫的 plan_adjust.json（每日 8:00 動態補量）；check_actual：本週／過去週用「實際＋剩餘」檢查。"""
    today = today or dt.date.today()
    adj = {}
    if apply_adjust:
        import adjust_week
        adj = adjust_week.load()
    days = []
    for d, kind, t, km, pace, tm, note in DAYS:
        dd = dt.date.fromisoformat(d)
        if d in adj and kind == "run":
            a = adj[d]; km = a["km"]; km = int(km) if km == int(km) else km
            note = f"本週跑量不足，由 {a['from']:g} km 加到 {km:g} km（{a['set'][5:].replace('-', '/')} 動態補量）；" + note
        days.append(dict(date=d, weekday="週"+WD[dd.weekday()], kind=kind, type=t, km=km, pace=pace, treadmill=tm, note=note,
                         week=week_key(dd).isoformat()))
    weeks = {}
    for x in days:
        if x["date"] not in NOWEEK:
            weeks[x["week"]] = weeks.get(x["week"], 0) + x["km"]
    weekly = {k: round(v, 1) for k, v in weeks.items()}
    # 週總量檢查（2026-10-09 09:44 起）：還沒開始的週＝逐日計畫加總必須等於 WEEK_TOTAL；
    # 已開始的週（含本週）＝Strava 實際（今天以前／今天已跑）＋今天起還沒跑的計畫 km 與 WEEK_TOTAL 比較：
    # 不足時（補量已到上限或不補量的週）只印警告、不中斷 8:00 流程；超過（含補量進位到整數 km）不警告。
    import sys as _sys
    for k, v in WEEK_TOTAL.items():
        if k > today.isoformat() or not check_actual:
            if k > today.isoformat():
                assert abs(weekly[k] - v) < 1e-9, (k, weekly[k], v)
            continue
        import adjust_week
        from decimal import Decimal
        act, rem = adjust_week.week_status(k, today, [x for x in days if x["week"] == k and x["date"] not in NOWEEK], adjust_week.strava_runs())
        tot = act + sum(Decimal(str(x["km"])) for x in rem)
        if tot < Decimal(str(v)):     # 補量進位到整數 km 後可能超過目標，超過不警告
            print(f"週起 {k}：實際 {act} km＋剩餘計畫 {tot - act} km＝{tot} km，週目標 {v} km（差 {tot - Decimal(str(v))}）", file=_sys.stderr)
        weekly[k] = v                 # 每週目標（網頁目標線）＝WEEK_TOTAL，不因補量改變
    ks = sorted(WEEK_TOTAL)
    ref = None                        # 每週增幅 ≤10%：與前一個正常週（非減量週）比較；10/26 恢復週為起點
    for b in ks:
        if b < "2026-10-26": continue
        if ref is not None and b not in CUTBACK:
            assert WEEK_TOTAL[b] <= WEEK_TOTAL[ref] * 1.10 + 1e-9, (ref, b)
        if b not in CUTBACK or ref is None: ref = b
    # 2026-10-09 使用者：週二、四、六固定重訓（自己的課表，課表只標「重訓」）。10/9 起每個週二／四／六必須是 kind=str、type=重訓，
    # 例外：STR_EXEMPT（賽前一天維持休息）。同一天可以有多筆（例如 10/31 重訓＋輕鬆跑），只要其中一筆是重訓。舊規則「每週 2 次肌力＋1 天完全休息」停用。
    for d0 in sorted({x["date"] for x in days}):
        dd = dt.date.fromisoformat(d0)
        if d0 >= STR_FROM and dd.weekday() in STR_WEEKDAYS and d0 not in STR_EXEMPT:
            assert any(x["kind"] == "str" and x["type"] == "重訓" for x in days if x["date"] == d0), d0
    nxt = next_goal(dt.date.today())  # 建置當天的下一個目標（網頁會自己用瀏覽器日期重算）
    return dict(race_date=nxt["date"], race_name=nxt["name"], goals=GOALS, week_phase=WEEK_PHASE, days=days,
                weekly_km=weekly, test_plan=TEST_PLAN, test_title="10K 自我測試策略（12/27 目標 54:59、2/21 目標 52:59）", long_goal=LONG_GOAL,
                race_title="3/21 2XU 半馬賽日策略（目標 2:00:00 以內）",
                assumptions=ASSUMPTIONS, race_plan=RACE_PLAN, predict=PREDICT, caveat=CAVEAT, checkin=CHECKIN)

def to_md(p):
    L = ["# 訓練計畫（2026-10-01 ～ 2027-03-21）：10K 分階段（55 → 53 → 破 50）＋ 2XU 半馬破 2", "",
         "> 目標（2026-10-25 設定）：10K 分階段：12/27 54:59（5:29/km）→ 2/21 52:59（5:17/km）→ 長期 49:59（半馬後）｜2027-03-21 2XU Singapore Compression Run 半馬 2:00:00 以內（5:41/km）｜跑步機一律 0% 坡度", "",
         "## 重要提醒", "", p["caveat"], "", "## 背景與假設", ""]
    L += [f"- {a}" for a in p["assumptions"]]
    L += ["", "## 逐日計畫", "", "| 日期 | 星期 | 內容 | 距離 (km) | 路跑配速 | 跑步機（0%） | 說明 |", "|---|---|---|---|---|---|---|"]
    for x in p["days"]:
        km = "—" if not x["km"] else (f'{x["km"]:g}')
        L.append(f'| {x["date"]} | {x["weekday"]} | {x["type"]} | {km} | {x["pace"] or "—"} | {x["treadmill"] or "—"} | {x["note"]} |')
    L += ["", "## 每週跑量（週一～週日；10/25、3/21 比賽當天不計入）", ""]
    for k, v in p["weekly_km"].items():
        ph = p["week_phase"].get(k)
        L.append(f"- 週起 {k}：{v:.1f} km" + (f"（{ph}）" if ph else "") + ("（含 10/1 起的部分週）" if k == "2026-09-28" else ""))
    L += ["", "## " + p["race_title"], ""]
    L += [f"{i}. {s}" for i, s in enumerate(p["race_plan"], 1)]
    L += ["", "## " + p["test_title"], ""]
    L += [f"{i}. {s}" for i, s in enumerate(p["test_plan"], 1)]
    c = p["checkin"]
    L += ["", "## " + c["title"], ""] + [f"- {x}" for x in c["items"]]
    L += ["", "長期目標：" + "；".join(c["goals"]), "", "安全規則：" + "；".join(c["rules"])]
    return "\n".join(L) + "\n"

